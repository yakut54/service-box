      <li>обеспечивать техническую поддержку по электронной почте info@yakut54.ru в рабочие дни с 9:00 до 18:00 по московскому времени;</li>
      <li>хранить данные Заказчика в течение срока действия договора и 30 (тридцати) дней после его расторжения;</li>
      <li>не передавать данные Заказчика третьим лицам, за исключением случаев, предусмотренных настоящим договором и действующим законодательством РФ.</li>
    </ul>
    <p><strong>Заказчик обязуется:</strong></p>
    <ul>
      <li>использовать Платформу только в законных целях, в соответствии с законодательством Российской Федерации;</li>
      <li>не осуществлять действия, направленные на нарушение нормальной работы Платформы;</li>
      <li>своевременно производить оплату услуг;</li>
      <li>при использовании Платформы для обработки персональных данных третьих лиц — соблюдать требования Федерального закона № 152-ФЗ «О персональных данных»;</li>
      <li>нести ответственность за законность размещаемого в Платформе контента и за деятельность собственного интернет-магазина.</li>
