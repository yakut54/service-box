    </ul>

    <h2>5. Ответственность сторон</h2>
    <p>Исполнитель несёт ответственность за работоспособность Платформы в пределах, установленных настоящим договором. Совокупная ответственность Исполнителя по любым претензиям Заказчика ограничена суммой, фактически оплаченной Заказчиком за последний расчётный период.</p>
    <p>Исполнитель не несёт ответственности за:</p>
    <ul>
      <li>упущенную выгоду и косвенные убытки Заказчика;</li>
      <li>содержание магазина Заказчика и его взаимоотношения с покупателями;</li>
      <li>сбои в работе платёжных систем и банков, не зависящие от Исполнителя;</li>
      <li>перебои в работе сети Интернет у Заказчика или его покупателей;</li>
      <li>утрату данных вследствие действий самого Заказчика.</li>
    </ul>
    <p>Заказчик несёт ответственность за нарушение условий настоящего договора, включая незаконное использование Платформы, нарушение прав потребителей и третьих лиц при ведении торговой деятельности.</p>

    <h2>6. Интеллектуальная собственность</h2>
    <p>Платформа ServiceBox и все её компоненты являются объектами интеллектуальной собственности Исполнителя. Настоящий договор предоставляет Заказчику неисключительную лицензию на использование Платформы в рамках выбранного тарифного плана. Заказчик не приобретает каких-либо прав собственности на Платформу или её части.</p>
    <p>Контент (товары, описания, изображения), размещаемый Заказчиком, остаётся интеллектуальной собственностью Заказчика или третьих лиц, у которых Заказчик приобрёл соответствующие права. Заказчик несёт полную ответственность за законность размещаемого контента.</p>

    <h2>7. Порядок расторжения договора</h2>
    <p>Заказчик вправе расторгнуть договор в любое время, удалив учётную запись или обратившись к Исполнителю по адресу info@yakut54.ru. При досрочном расторжении по инициативе Заказчика возврат оплаченных средств за неиспользованный период не производится.</p>
    <p>Исполнитель вправе расторгнуть договор в одностороннем порядке с немедленным прекращением доступа к Платформе в случае:</p>
    <ul>
      <li>нарушения Заказчиком условий настоящего договора;</li>
      <li>использования Платформы в целях, нарушающих законодательство Российской Федерации;</li>
      <li>неоплаты услуг по истечении 7 (семи) дней с момента окончания оплаченного периода.</li>
    </ul>
    <p>По истечении 30 дней после прекращения доступа данные Заказчика могут быть безвозвратно удалены.</p>

    <h2>8. Порядок разрешения споров</h2>
    <p>Все споры и разногласия, возникающие в связи с исполнением настоящего договора, разрешаются путём переговоров. При невозможности достичь соглашения — в судебном порядке по месту нахождения Исполнителя в соответствии с законодательством Российской Федерации.</p>
    <p>Направление претензии в адрес Исполнителя является обязательным условием до обращения в суд. Срок ответа на претензию — 15 (пятнадцать) рабочих дней с момента её получения.</p>

    <h2>9. Прочие условия</h2>
    <p>Исполнитель вправе вносить изменения в условия настоящей оферты, публикуя новую редакцию по адресу yakut54.ru/offer. Продолжение использования Платформы после публикации изменений означает согласие Заказчика с новыми условиями. Если Заказчик не согласен с изменениями — он вправе расторгнуть договор в порядке, установленном разделом 7.</p>
    <p>Настоящий договор регулируется законодательством Российской Федерации. К отношениям, не урегулированным договором, применяются нормы Гражданского кодекса РФ, Федерального закона № 149-ФЗ «Об информации, информационных технологиях и о защите информации» и иного применимого законодательства.</p>

