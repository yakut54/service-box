    <h2>1. Общие положения</h2>
    <p>Настоящий документ является официальным предложением (публичной офертой) индивидуального предпринимателя [ФИО], действующего на основании свидетельства о государственной регистрации ОГРНИП [ОГРНИП] (далее — «Исполнитель»), заключить договор на оказание услуг доступа к программному обеспечению «ServiceBox» на условиях, изложенных ниже.</p>
    <p>Настоящая оферта адресована физическим и юридическим лицам, индивидуальным предпринимателям, намеревающимся использовать платформу ServiceBox для ведения коммерческой деятельности (далее — «Заказчик»).</p>
    <p>В соответствии со статьёй 438 Гражданского кодекса Российской Федерации безоговорочное принятие (акцепт) условий настоящей оферты осуществляется путём регистрации на платформе и/или оплаты выбранного тарифного плана. С момента акцепта Заказчик считается ознакомившимся и согласившимся со всеми условиями настоящего договора.</p>

    <h2>2. Предмет договора</h2>
    <p>Исполнитель обязуется предоставить Заказчику доступ к программному обеспечению «ServiceBox», размещённому в сети Интернет по адресу yakut54.ru (далее — «Платформа»), а Заказчик обязуется оплатить услуги в соответствии с выбранным тарифным планом.</p>
    <p>Платформа предоставляет следующий функционал:</p>
    <ul>
      <li>создание и управление интернет-магазином (каталог товаров, приём заказов);</li>
      <li>система онлайн-записи на услуги;</li>
      <li>встраиваемый виджет для сторонних сайтов;</li>
      <li>CRM-инструменты: управление клиентами, дисконтные программы, отзывы;</li>
      <li>приём платежей через сертифицированного платёжного оператора ЮКасса;</li>
      <li>аналитика и статистика продаж.</li>
    </ul>
    <p>Исполнитель вправе изменять функциональный состав Платформы, уведомляя Заказчика не менее чем за 7 (семь) рабочих дней в случае существенного уменьшения функционала.</p>

    <h2>3. Стоимость и порядок оплаты</h2>
    <p>Стоимость услуг определяется действующими тарифными планами, опубликованными на странице подписки. Исполнитель вправе изменять тарифы с предварительным уведомлением Заказчика за 14 (четырнадцать) календарных дней. Для действующих подписок изменение тарифов применяется со следующего оплачиваемого периода.</p>
    <p>Оплата осуществляется в российских рублях посредством эквайринга ЮКасса (НКО «ЮМани», лицензия ЦБ РФ) с использованием банковской карты или иных поддерживаемых методов оплаты. Оплата считается произведённой с момента получения Исполнителем подтверждения об успешном платеже от платёжного сервиса.</p>
    <p>Услуги предоставляются на условиях предоплаты. Срок доступа к Платформе начинается с момента получения оплаты и составляет период, соответствующий выбранному тарифу.</p>
    <p>Налогообложение осуществляется в соответствии с применяемой Исполнителем системой налогообложения. Исполнитель выдаёт кассовый чек в электронной форме в соответствии с требованиями Федерального закона № 54-ФЗ «О применении контрольно-кассовой техники».</p>

