import 'package:flutter_test/flutter_test.dart';
import 'package:mobile/core/format.dart';

void main() {
  group('pluralRu', () {
    test('1, 21, 101 — именительный единственного', () {
      expect(pluralRu(1, 'сообщение', 'сообщения', 'сообщений'), 'сообщение');
      expect(pluralRu(21, 'сообщение', 'сообщения', 'сообщений'), 'сообщение');
      expect(pluralRu(101, 'сообщение', 'сообщения', 'сообщений'), 'сообщение');
    });

    test('2, 3, 4, 22 — родительный единственного', () {
      expect(pluralRu(2, 'сообщение', 'сообщения', 'сообщений'), 'сообщения');
      expect(pluralRu(3, 'сообщение', 'сообщения', 'сообщений'), 'сообщения');
      expect(pluralRu(4, 'сообщение', 'сообщения', 'сообщений'), 'сообщения');
      expect(pluralRu(22, 'сообщение', 'сообщения', 'сообщений'), 'сообщения');
    });

    test('5-20, 6 — родительный множественного (баг с реального устройства: '
        '"Удалить 6 сообщения?" должно быть "Удалить 6 сообщений?")', () {
      expect(pluralRu(5, 'сообщение', 'сообщения', 'сообщений'), 'сообщений');
      expect(pluralRu(6, 'сообщение', 'сообщения', 'сообщений'), 'сообщений');
      expect(pluralRu(11, 'сообщение', 'сообщения', 'сообщений'), 'сообщений');
      expect(pluralRu(14, 'сообщение', 'сообщения', 'сообщений'), 'сообщений');
      expect(pluralRu(20, 'сообщение', 'сообщения', 'сообщений'), 'сообщений');
    });
  });
}
